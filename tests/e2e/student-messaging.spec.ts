test('local AI demo summaries and explanations preserve human messages and never send automatically', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: /Research Methods/ }).click()
  const studentThread = page.getByRole('region', { name: 'Research Methods conversation' })
  const originalReply = 'A couple can be useful. Keep them focused on your research question.'
  const replyBubble = studentThread.locator('.message-group').filter({ hasText: originalReply })
  const messageCountBeforeActions = await studentThread.locator('article.message').count()
  await replyBubble.getByRole('button', { name: 'Explain simply' }).click()
  await expect(replyBubble.getByRole('region', { name: 'AI explanation · Demo' })).toBeVisible()
  await expect(replyBubble.locator('article.message').getByText(originalReply, { exact: true })).toBeVisible()
  await expect(replyBubble.getByRole('region', { name: 'AI explanation · Demo' }).getByText(`In simpler words: ${originalReply}`, { exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Voice message demo' }).click()
  const voicePreview = page.getByRole('status').filter({ hasText: 'Voice message · Demo' })
  await expect(voicePreview).toBeVisible()
  await expect(voicePreview.getByText('Transcript · Demo')).toBeVisible()
  await expect(voicePreview.getByText('No audio is recorded or uploaded. This local preview does not send a message.')).toBeVisible()
  await expect(studentThread.locator('article.message')).toHaveCount(messageCountBeforeActions)
  await expect(page.getByRole('button', { name: 'Send question' })).toBeDisabled()

  const longQuestion = 'I reviewed the lecture notes and tried the exercise twice. I am unsure how the two approaches differ, and I would appreciate clarification about which steps to show in my work. '.repeat(2)
  await page.getByRole('button', { name: 'Inbox' }).click()
  await page.getByRole('button', { name: /Business Statistics/ }).click()
  await page.getByLabel('Ask a question about Business Statistics').fill(longQuestion)
  await page.getByRole('button', { name: 'Send question' }).click()
  await expect(page.getByRole('region', { name: 'Business Statistics conversation' }).getByRole('region', { name: 'AI summary · Demo' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Instructor', exact: true }).click()
  const longQuestionCard = page.getByRole('button', { name: /Business Statistics/ }).filter({ hasText: 'I reviewed the lecture notes' })
  await longQuestionCard.click()
  const instructorThread = page.getByRole('region', { name: 'Business Statistics conversation' })
  const shortMessage = instructorThread.locator('.message-group').filter({ hasText: 'I have a question about the lecture notes.' })
  await expect(shortMessage.getByRole('button', { name: 'Generate summary' })).toHaveCount(0)
  const longMessage = instructorThread.locator('.message-group').filter({ hasText: 'I reviewed the lecture notes' })
  await expect(longMessage.getByRole('button', { name: 'Generate summary' })).toBeVisible()
  await expect(longMessage.getByRole('button', { name: 'Explain simply' })).toHaveCount(0)
  const countBeforeSummary = await instructorThread.locator('article.message').count()
  await longMessage.getByRole('button', { name: 'Generate summary' }).click()
  await expect(longMessage.getByRole('region', { name: 'AI summary · Demo' })).toBeVisible()
  await expect(longMessage.getByText('Deterministic local demo text; no AI model was contacted.')).toBeVisible()
  await expect(longMessage.locator('article.message')).toContainText(longQuestion.trim())
  await expect(instructorThread.locator('article.message')).toHaveCount(countBeforeSummary)

  await page.getByRole('button', { name: 'Student', exact: true }).click()
  const summarizedStudentCard = page.getByRole('button', { name: /Business Statistics/ }).filter({ hasText: 'I reviewed the lecture notes' })
  await summarizedStudentCard.click()
  const summarizedStudentThread = page.getByRole('region', { name: 'Business Statistics conversation' })
  const summarizedStudentMessage = summarizedStudentThread.locator('.message-group').filter({ hasText: 'I reviewed the lecture notes' })
  await expect(summarizedStudentMessage.getByRole('region', { name: 'AI summary · Demo' })).toBeVisible()
  await expect(summarizedStudentMessage.locator('article.message')).toContainText(longQuestion.trim())
})

